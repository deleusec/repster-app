#!/usr/bin/env python3
"""Vendors the Fluent 3D emoji listed in `selection.txt`.

Downloads each image from `github.com/microsoft/fluentui-emoji` (MIT), resamples
it from 256 to 128 px (enough for a 44 pt tile at 3x) as lossy WebP, and
regenerates `lib/core/emoji/fluent_emoji_catalog.dart` and the English labels
in `lib/i18n/emoji_en.i18n.json`. Other locales are written by hand; the script
lists the keys they are missing.

    python3 tool/fluent_emoji/fetch.py [--work DIR]

`--work` is where raw downloads land (default: a temp dir).
"""

import argparse
import json
import re
import subprocess
import sys
import tempfile
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SELECTION = Path(__file__).with_name("selection.txt")
ASSETS = ROOT / "assets" / "emoji" / "fluent"
CATALOG = ROOT / "lib" / "core" / "emoji" / "fluent_emoji_catalog.dart"
I18N = ROOT / "lib" / "i18n"
API = "https://api.github.com/repos/microsoft/fluentui-emoji"
RAW = "https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/assets"
SIZE = 128
LOCALES = ["en", "fr", "es", "de", "it"]

GROUPS_EN = {
    "sport": "Sports & training",
    "body": "Body & gestures",
    "energy": "Energy & symbols",
    "faces": "Faces",
    "hearts": "Hearts",
    "animals": "Animals",
    "food": "Food & drinks",
    "nature": "Nature & weather",
    "places": "Places & travel",
    "objects": "Objects & tools",
}


def key_of(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def read_selection() -> list[tuple[str, str]]:
    group = None
    out = []
    for raw in SELECTION.read_text().splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            tag = line[1:].strip()
            if tag in GROUPS_EN:
                group = tag
            continue
        if group is None:
            sys.exit(f"'{line}' appears before any '# <group>' header")
        out.append((line, group))
    return out


def fetch_json(url: str):
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.load(r)


def asset_folders() -> dict[str, str]:
    root = fetch_json(f"{API}/git/trees/main")
    sha = next(e["sha"] for e in root["tree"] if e["path"] == "assets")
    tree = fetch_json(f"{API}/git/trees/{sha}")
    return {e["path"].lower(): e["path"] for e in tree["tree"]}


def download(folder: str, dest: Path) -> bool:
    base = folder.lower().replace(" ", "_")
    quoted = urllib.parse.quote(folder)
    for path in (f"{quoted}/3D/{base}_3d.png", f"{quoted}/Default/3D/{base}_3d_default.png"):
        try:
            with urllib.request.urlopen(f"{RAW}/{path}", timeout=60) as r:
                dest.write_bytes(r.read())
            return True
        except urllib.error.HTTPError as e:
            if e.code != 404:
                raise
    return False


def convert(src: Path, dest: Path) -> None:
    im = Image.open(src).convert("RGBA")
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    im.save(dest, "WEBP", quality=90, method=6, alpha_quality=100)


ORDINALS = {"1st": "first", "2nd": "second", "3rd": "third"}


def ident_of(key: str) -> str:
    words = [ORDINALS.get(w, w) for w in key.split("-")]
    return words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])


def write_catalog(entries: list[tuple[str, str, str]]) -> None:
    lines = [
        "// Generated by tool/fluent_emoji/fetch.py from tool/fluent_emoji/selection.txt.",
        "// Do not edit by hand.",
        "",
        "part of 'fluent_emoji.dart';",
        "",
        "/// Every vendored emoji as a named constant, for code that refers to one",
        "/// (defaults, fallbacks). The picker iterates [FluentEmoji.all] instead.",
        "abstract final class FluentEmojis {",
    ]
    for key, group, _ in entries:
        lines.append(
            f"  static const {ident_of(key)} = FluentEmoji._('{key}', FluentEmojiGroup.{group});"
        )
    lines += ["}", "", "const List<FluentEmoji> _catalog = [", ]
    for key, _, _ in entries:
        lines.append(f"  FluentEmojis.{ident_of(key)},")
    lines += ["];", ""]
    CATALOG.write_text("\n".join(lines))
    subprocess.run(["dart", "format", str(CATALOG)], check=True, capture_output=True)


def write_english(entries: list[tuple[str, str, str]]) -> None:
    labels = {key: name[0].upper() + name[1:] for key, _, name in entries}
    (I18N / "emoji_en.i18n.json").write_text(
        json.dumps({"groups": GROUPS_EN, "labels": labels}, indent=2, ensure_ascii=False) + "\n"
    )


def report_missing(keys: list[str]) -> None:
    for locale in LOCALES[1:]:
        path = I18N / f"emoji_{locale}.i18n.json"
        if not path.exists():
            print(f"{path.name}: missing file")
            continue
        data = json.loads(path.read_text())
        have = set(data.get("labels", {}))
        missing = [k for k in keys if k not in have]
        extra = sorted(have - set(keys))
        if missing or extra:
            print(f"{path.name}: {len(missing)} missing, {len(extra)} unused")
            for k in missing:
                print(f"  - {k}")
            for k in extra:
                print(f"  + {k}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", type=Path)
    args = ap.parse_args()
    work = args.work or Path(tempfile.mkdtemp(prefix="fluent-"))
    work.mkdir(parents=True, exist_ok=True)
    ASSETS.mkdir(parents=True, exist_ok=True)

    selection = read_selection()
    folders = asset_folders()
    entries = []
    jobs = []
    for name, group in selection:
        folder = folders.get(name.lower())
        if folder is None:
            print(f"not in the collection: {name}")
            continue
        key = key_of(name)
        entries.append((key, group, folder))
        jobs.append((key, folder))

    def run(job):
        key, folder = job
        dest = ASSETS / f"{key}.webp"
        if dest.exists():
            return key, True
        raw = work / f"{key}.png"
        if not raw.exists() and not download(folder, raw):
            return key, False
        convert(raw, dest)
        return key, True

    with ThreadPoolExecutor(max_workers=12) as pool:
        results = dict(pool.map(run, jobs))
    failed = [k for k, ok in results.items() if not ok]
    for k in failed:
        print(f"no 3D image: {k}")
    entries = [e for e in entries if results.get(e[0])]

    wanted = {e[0] for e in entries}
    for stale in ASSETS.glob("*.webp"):
        if stale.stem not in wanted:
            stale.unlink()
            print(f"removed stale asset: {stale.name}")

    write_catalog(entries)
    write_english(entries)
    report_missing([e[0] for e in entries])
    total = sum(p.stat().st_size for p in ASSETS.glob("*.webp"))
    print(f"{len(entries)} emoji, {total / 1024:.0f} KiB")


if __name__ == "__main__":
    main()
